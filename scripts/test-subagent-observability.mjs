import assert from "node:assert/strict";
import { mergeSubagentDetail, subagentEventTime } from "../src/features/workbench/subagent-observability.js";
import { view } from "../src/shared/state.js";
import { renderOrcaRightDockMarkup } from "../src/features/workbench/right-dock.js";
import { createStageSubagentTracker } from "../src/server/subagent-tracker.mjs";

const summary = { id: "one", status: "completed", updatedAt: "2026-11-12T10:00:02Z" };
const oldDetail = { id: "one", status: "running", updatedAt: "2026-11-12T10:00:01Z", events: [{ text: "read file" }] };
const merged = mergeSubagentDetail(summary, oldDetail);
assert.equal(merged.status, "completed");
assert.equal(merged.events[0].text, "read file");
const newer = mergeSubagentDetail(summary, { ...oldDetail, status: "failed", updatedAt: "2026-11-12T10:00:03Z" });
assert.equal(newer.status, "failed");
assert.equal(subagentEventTime("not a date"), "");
assert.ok(subagentEventTime("2026-11-12T10:00:00Z"));
view.page = "chat";
view.selected = "task";
view.chatDrawerTab = "subagents";
view.state = { settings: {}, workspaces: [{ id: "workspace", name: "Project", path: "D:/test" }], tasks: [{ id: "task", workspaceId: "workspace", updatedAt: summary.updatedAt, subagents: [summary] }] };
view.connectors = {};
view.taskSubagentDetailCache = { task: { updatedAt: summary.updatedAt, subagents: [oldDetail] } };
let html = renderOrcaRightDockMarkup();
assert.match(html, /Hoàn tất/);
assert.doesNotMatch(html, /1 đang chạy/);
assert.match(html, /read file/);
view.chatDrawerTab = "overview";
html = renderOrcaRightDockMarkup();
assert.match(html, /TỔNG QUAN PHIÊN/);
assert.match(html, /Chỉ hiển thị lệnh có ID/);
const task = { subagents: [], currentRound: 1 };
const tracker = createStageSubagentTracker({ task, harness: "codex", stage: "build" });
for (let i = 0; i < 65; i++) tracker.upsertSubagent({ externalId: `agent-${i}`, status: "running" });
assert.equal(task.subagents.length, 65, "Active subagents must not be evicted at the history limit");
assert.ok(tracker.findByExternalId("agent-0"));
tracker.upsertSubagent({ externalId: "agent-0", status: "completed" });
assert.equal(task.subagents.length, 64);
assert.ok(tracker.findByExternalId("agent-1"));
const unfinishedTask = { subagents: [] };
const unfinishedTracker = createStageSubagentTracker({ task: unfinishedTask, harness: "claude", stage: "build" });
unfinishedTracker.upsertSubagent({ externalId: "still-running", status: "running" });
unfinishedTracker.finalizeStageSubagents("completed");
assert.equal(unfinishedTask.subagents[0].status, "unknown", "Parent completion does not prove the subagent succeeded");
console.log("Subagent activity snapshot ordering passed.");
